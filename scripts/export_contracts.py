"""Regenerate the generated contract files: contracts/openapi.yaml and decision.schema.json.

Source of truth: twinguard-backend/app/schemas.py + routers, and the core DecisionReport model.
Run after changing either, commit the result. `check_contracts.py` fails if they drift.
"""
import json

import _setup  # noqa: F401  (must come before the app imports)
import yaml

from _setup import CONTRACTS
from app.config import Settings
from app.db import MemoryDb
from app.main import create_app
from twinguard_core import DecisionReport

NOTE = "GENERATED by scripts/export_contracts.py - do not edit by hand."

DECISION_NOTE = (
    NOTE + " Two shapes exist today. DecisionReport = live agent path (request.report), "
    "free-text reasons, no reason_code. ScenarioReport = evaluated path (eval conditions), "
    "has reason_code, findings and simulation samples. snapshot_version lives on the request, "
    "not on the report. Gaps vs the original brief: no reason_code/rules/snapshot_version on "
    "DecisionReport; core must add them before the UI can rely on them."
)

SIMULATION_SUMMARY = {
    "type": "object",
    "properties": {
        "unsafe": {"type": "boolean"},
        "max_warehouse_capacity_pct": {"type": "number"},
        "stockout_count": {"type": "number"},
        "violated_rules": {"type": "array", "items": {"type": "string"}},
        "kpis": {"type": "object", "additionalProperties": {"type": "number"}},
        "warnings": {"type": "array", "items": {"type": "string"}},
        "possible_hidden_po_sampled": {"type": "boolean"},
    },
    "required": ["unsafe", "violated_rules", "kpis", "warnings"],
}


def render() -> dict:
    spec = create_app(Settings(_env_file=None, env="dev"), MemoryDb()).openapi()
    rep = DecisionReport.model_json_schema(ref_template="#/$defs/{model}")
    defs = rep.pop("$defs")
    defs["DecisionReport"] = rep
    defs["SimulationSummary"] = SIMULATION_SUMMARY
    defs["ScenarioReport"] = {
        "type": "object",
        "properties": {
            "decision": {"enum": ["approve", "block", "human_review"]},
            "detail": {
                "type": "object",
                "properties": {
                    "reason_code": {"type": "string"},
                    "findings": {"type": "array", "items": {"$ref": "#/$defs/DataQualityIssue"}},
                    "simulations": {"type": "array", "items": {"$ref": "#/$defs/SimulationSummary"}},
                },
                "required": ["reason_code", "findings", "simulations"],
            },
        },
        "required": ["decision", "detail"],
    }
    schema = {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "$id": "decision.schema.json",
        "$comment": DECISION_NOTE,
        "oneOf": [{"$ref": "#/$defs/DecisionReport"}, {"$ref": "#/$defs/ScenarioReport"}],
        "$defs": defs,
    }
    return {
        "openapi.yaml": f"# {NOTE}\n" + yaml.safe_dump(spec, sort_keys=False, allow_unicode=True),
        "decision.schema.json": json.dumps(schema, indent=2) + "\n",
    }


if __name__ == "__main__":
    for name, text in render().items():
        (CONTRACTS / name).write_text(text, encoding="utf-8", newline="\n")
        print("wrote", name)
